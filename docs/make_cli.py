"""Generate the command-line reference from the parser itself.

Every block in `docs/cli-reference.md` is `--help` output captured from
the live argparse tree, so a flag cannot appear here unless it exists.

    python3 docs/make_cli.py            # rewrite docs/cli-reference.md
    python3 docs/make_cli.py --check    # exit 1 if it would change

`COLUMNS` is pinned before anything is formatted. argparse wraps help text
to the terminal width, so without that the file would differ between a
wide terminal and a narrow one and the freshness test in
`tests/test_generated_docs.py` would fail for no reason at all.
"""

from __future__ import annotations

import os

os.environ["COLUMNS"] = "88"  # before argparse reads the terminal width

import argparse  # noqa: E402
import sys  # noqa: E402
from pathlib import Path  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from stabilis.cli import build_parser  # noqa: E402

OUT = Path(__file__).resolve().parent / "cli-reference.md"

BANNER = (
    "<!-- Generated by docs/make_cli.py from the argparse tree. Do not edit:\n"
    "     edit the parser in src/stabilis/cli/ and regenerate. -->"
)


def walk(parser: argparse.ArgumentParser, path: tuple[str, ...] = ()
         ) -> list[tuple[tuple[str, ...], str, argparse.ArgumentParser]]:
    """Every command in the tree, depth first, with its one-line summary.

    Subcommand summaries live on the parent's `_choices_actions`, not on
    the child parser, which is why the recursion carries them down rather
    than reading them off the parser it is about to format.
    """
    found: list[tuple[tuple[str, ...], str, argparse.ArgumentParser]] = []
    for action in parser._actions:
        if not isinstance(action, argparse._SubParsersAction):
            continue
        summaries = {c.dest: (c.help or "") for c in action._choices_actions}
        for name, child in action.choices.items():
            found.append((path + (name,), summaries.get(name, ""), child))
            found += walk(child, path + (name,))
    return found


def render() -> str:
    parser = build_parser()
    commands = walk(parser)
    lines = [
        BANNER, "",
        "# Command-line reference", "",
        "Captured from `stabilis --help` and every subcommand's `--help`.",
        "The library API is documented separately, in [api/index.md]"
        "(api/index.md).", "",
        "## Commands", "",
        "| Command | Does |", "| --- | --- |",
    ]
    for path, summary, _ in commands:
        joined = " ".join(path)
        anchor = "stabilis-" + "-".join(path)
        text = summary.replace("%%", "%").replace("|", r"\|")
        lines.append(f"| [`stabilis {joined}`](#{anchor}) | {text} |")
    lines += ["", "---", "", "## `stabilis`", "", "```",
              parser.format_help().rstrip(), "```", ""]
    for path, summary, child in commands:
        joined = " ".join(path)
        lines += [f"## `stabilis {joined}`", ""]
        if summary:
            lines += [summary.replace("%%", "%").capitalize() + ".", ""]
        lines += ["```", child.format_help().rstrip(), "```", ""]
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="do not write; exit 1 if the page is stale")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"stale: {OUT}", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
