"""Generate the API reference from the source tree.

The reference is *derived*, never typed: every signature and every
docstring in `docs/api/` is read out of `src/stabilis` at generation time,
so a page cannot describe a function that no longer has that argument.

    python3 docs/make_api.py            # rewrite docs/api/
    python3 docs/make_api.py --check    # exit 1 if it would change

Reading is done with `ast`, not by importing the package. That matters for
two reasons: `stabilis.plot` and `stabilis.report` want matplotlib, which
is optional and absent in the bare environment, and an import-based tool
would silently emit a *different* reference depending on what happened to
be installed. Parsing the source gives the same bytes everywhere, which is
what makes the freshness test in `tests/test_generated_docs.py` meaningful.

The public surface is `__all__`, module by module -- the same promise the
package makes to callers. Anything not named there is internal and is
deliberately absent here.
"""

from __future__ import annotations

import argparse
import ast
import sys
from dataclasses import dataclass
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent / "src" / "stabilis"
OUT = Path(__file__).resolve().parent / "api"

BANNER = (
    "<!-- Generated by docs/make_api.py from the source tree. Do not edit:\n"
    "     edit the docstring in src/stabilis and regenerate. -->"
)

# Which modules land on which page, and what the page is for. Order is the
# reading order of the index, which follows the pipeline: get data in,
# prepare it, estimate, quantify, combine, fit, then get it back out.
GROUPS: tuple[tuple[str, str, str], ...] = (
    ("core", "Core types and data handling",
     "Series types, provenance, the tau grid, editing and synthesis -- "
     "everything that is not itself an estimator."),
    ("io", "Reading and writing records",
     "Text and binary records in, records out, and the timebase they carry."),
    ("stats", "Estimators, uncertainty and spectra",
     "The variance family, confidence intervals, noise identification, "
     "power spectra and spurs."),
    ("multi", "Several channels at once",
     "Alignment, cross-variance, the N-cornered hat and the correlation "
     "matrix."),
    ("fitting", "Fitting a model to a curve",
     "Power-law and Gauss-Markov models fitted to a measured sigma-tau "
     "curve, with a covariance-aware uncertainty."),
    ("stream", "Measurements that have not finished",
     "Incremental estimation over a growing record, and dynamic stability."),
    ("bench", "The measurement setup",
     "Sources, devices and channels as a graph, and what that graph can "
     "and cannot determine."),
    ("export", "Getting results back out",
     "Sigma-tau tables, Stable32-shaped blocks and self-describing "
     "bundles."),
    ("report", "The measurement report",
     "The customer-facing HTML report and its conformity verdict."),
    ("validate", "Validation machinery",
     "The exact-rational oracle and the evidence report."),
    ("plot", "Plotting",
     "Matplotlib figures. Optional dependency, never required for a "
     "number."),
    ("gui", "The local browser page",
     "The request handling behind `stabilis gui`."),
)

# Root-level modules that belong on the `core` page. `cli/` is documented
# by docs/make_cli.py instead -- `_group_of` returns None for anything
# dotted `cli.*`, so its submodules stay out too -- and the
# leading-underscore modules are
# implementation detail rather than public surface.
CORE_MODULES = (
    "types", "provenance", "log", "registry", "tau", "preprocess", "edit",
    "synth", "mask", "powerlaw_coeffs", "reference", "docs",
)
SKIP_MODULES = ("cli", "_nnls", "_specfun")


@dataclass(frozen=True)
class Entry:
    """One public name: what it is, where it lives, what it says."""

    name: str
    kind: str  # "function" | "class" | "constant" | "alias"
    module: str  # dotted, e.g. "stats.core"
    signature: str
    doc: str
    members: tuple[tuple[str, str, str], ...]  # (kind, signature, doc)


@dataclass(frozen=True)
class Module:
    """A parsed module and the public names it defines."""

    dotted: str
    doc: str
    exported: tuple[str, ...]
    entries: tuple[Entry, ...]


def _literal_all(tree: ast.Module) -> tuple[str, ...]:
    """The module's `__all__`, or () if it has none."""
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "__all__" for t in node.targets
        ):
            return tuple(ast.literal_eval(node.value))
    return ()


def _signature(node: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    """`name(args) -> return`, exactly as the source declares it."""
    args = ast.unparse(node.args)
    returns = f" -> {ast.unparse(node.returns)}" if node.returns else ""
    return f"{node.name}({args}){returns}"


def _decorators(node: ast.ClassDef | ast.FunctionDef) -> list[str]:
    return [ast.unparse(d) for d in node.decorator_list]


def _class_members(node: ast.ClassDef) -> tuple[tuple[str, str, str], ...]:
    """Fields, properties and methods of a class, in source order.

    Dataclass fields are AnnAssign, so they carry their declared type and
    default; properties and methods are FunctionDef and carry a signature.
    """
    members: list[tuple[str, str, str]] = []
    for item in node.body:
        if isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name):
            if item.target.id.startswith("_"):
                continue
            default = f" = {ast.unparse(item.value)}" if item.value else ""
            members.append(
                ("field",
                 f"{item.target.id}: {ast.unparse(item.annotation)}{default}",
                 "")
            )
        elif isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
            if item.name.startswith("_"):
                continue
            kind = "property" if "property" in _decorators(item) else "method"
            members.append((kind, _signature(item), ast.get_docstring(item) or ""))
    return tuple(members)


def _leading_comment(lines: list[str], lineno: int) -> str:
    """The contiguous `#` block immediately above a line, as prose.

    A module constant has no docstring, but in this codebase it almost
    always has a comment above it saying why the number is that number --
    which is the documentation, and would otherwise be dropped.
    """
    out: list[str] = []
    i = lineno - 2  # lineno is 1-based, and the line above is one back
    while i >= 0 and lines[i].lstrip().startswith("#"):
        out.append(lines[i].lstrip().lstrip("#").strip())
        i -= 1
    return " ".join(reversed(out))


def _binding(node: ast.Assign | ast.AnnAssign, dotted: str,
             lines: list[str]) -> Entry | None:
    """A module-level constant or alias, e.g. `ONE_SIGMA` or `detect_spurs`."""
    if isinstance(node, ast.AnnAssign):
        targets = [node.target]
    else:
        targets = list(node.targets)
    named = [t.id for t in targets if isinstance(t, ast.Name)]
    if len(named) != 1 or node.value is None:
        return None
    name = named[0]
    value = ast.unparse(node.value)
    kind = "alias" if isinstance(node.value, ast.Name) else "constant"
    return Entry(name, kind, dotted, f"{name} = {value}",
                 _leading_comment(lines, node.lineno), ())


def _entry(node: ast.AST, dotted: str) -> Entry | None:
    if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
        return Entry(node.name, "function", dotted, _signature(node),
                     ast.get_docstring(node) or "", ())
    if isinstance(node, ast.ClassDef):
        decorated = " ".join(f"@{d}" for d in _decorators(node))
        head = f"class {node.name}"
        signature = f"{decorated}\n{head}" if decorated else head
        return Entry(node.name, "class", dotted, signature,
                     ast.get_docstring(node) or "", _class_members(node))
    return None


def parse_module(path: Path) -> Module:
    """Public names and docstrings of one module, without importing it."""
    text = path.read_text(encoding="utf-8")
    tree = ast.parse(text)
    lines = text.splitlines()
    dotted = path.relative_to(SRC).with_suffix("").as_posix().replace("/", ".")
    dotted = dotted.removesuffix(".__init__")
    exported = _literal_all(tree)
    entries = []
    for node in tree.body:
        if isinstance(node, (ast.Assign, ast.AnnAssign)):
            entry = _binding(node, dotted, lines)
        else:
            entry = _entry(node, dotted)
        if entry is not None and entry.name in exported:
            entries.append(entry)
    return Module(dotted, ast.get_docstring(tree) or "", exported, tuple(entries))


def _group_of(module: Module) -> str | None:
    head, _, _ = module.dotted.partition(".")
    if head in (g for g, _, _ in GROUPS) and head not in ("core",):
        return head
    if module.dotted in SKIP_MODULES:
        return None
    return "core" if module.dotted in CORE_MODULES else None


def collect() -> dict[str, list[Module]]:
    """Every documented module, bucketed by page."""
    pages: dict[str, list[Module]] = {name: [] for name, _, _ in GROUPS}
    for path in sorted(SRC.rglob("*.py")):
        if path.name == "__init__.py" and path.parent == SRC:
            continue  # the top-level re-export list is the index's job
        module = parse_module(path)
        group = _group_of(module)
        if group is not None:
            pages[group].append(module)
    return pages


def _first_line(doc: str) -> str:
    return doc.strip().splitlines()[0] if doc.strip() else ""


def anchor_map(pages: dict[str, list[Module]]) -> dict[tuple[str, str, str], str]:
    """Where each name's heading actually lands, page by page.

    Two modules on one page can both export `available`, and the renderer
    emits `#### \\`available\\`` twice. Markdown viewers disambiguate by
    appending `-1`, `-2` in document order, so the index has to do the
    same arithmetic or its second link silently points at the first
    function.
    """
    anchors: dict[tuple[str, str, str], str] = {}
    for group, modules in pages.items():
        seen: dict[str, int] = {}
        for module in modules:
            for entry in module.entries:
                slug = entry.name.lower()
                count = seen.get(slug, 0)
                seen[slug] = count + 1
                anchors[group, module.dotted, entry.name] = (
                    slug if count == 0 else f"{slug}-{count}"
                )
    return anchors


def render_entry(entry: Entry) -> list[str]:
    """One public name as markdown: heading, signature, docstring, members."""
    out = [f"#### `{entry.name}`", "", "```python", entry.signature, "```", ""]
    if entry.kind == "alias":
        target = entry.signature.split("=", 1)[1].strip()
        out += [f"Another name for `{target}`.", ""]
    if entry.doc:
        out += [entry.doc.strip(), ""]
    fields = [m for m in entry.members if m[0] == "field"]
    others = [m for m in entry.members if m[0] != "field"]
    if fields:
        out += ["*Fields*", "", "```python"]
        out += [sig for _, sig, _ in fields]
        out += ["```", ""]
    for kind, sig, doc in others:
        label = "property" if kind == "property" else "method"
        out += [f"*{label}* `{sig}`", ""]
        if doc:
            out += [_first_line(doc), ""]
    return out


def render_page(group: str, title: str, blurb: str, modules: list[Module]) -> str:
    """A whole page: the modules of one subsystem, with a contents list."""
    lines = [BANNER, "", f"# {title}", "", blurb, "", "## Contents", ""]
    for module in modules:
        names = ", ".join(f"`{e.name}`" for e in module.entries)
        summary = _first_line(module.doc)
        lines.append(f"- **`stabilis.{module.dotted}`** -- {summary}")
        if names:
            lines.append(f"  <br>{names}")
    lines.append("")
    for module in modules:
        lines += ["---", "", f"## `stabilis.{module.dotted}`", ""]
        if module.doc:
            lines += [module.doc.strip(), ""]
        if not module.entries and module.exported:
            reexports = ", ".join(f"`{n}`" for n in module.exported)
            lines += [f"Re-exports: {reexports}.", ""]
        for entry in module.entries:
            lines += render_entry(entry)
    return "\n".join(lines).rstrip() + "\n"


def _top_level_names() -> tuple[str, ...]:
    tree = ast.parse((SRC / "__init__.py").read_text(encoding="utf-8"))
    return _literal_all(tree)


def render_index(pages: dict[str, list[Module]],
                 anchors: dict[tuple[str, str, str], str]) -> str:
    """The index: the frozen top-level API, then every public name."""
    promised = set(_top_level_names())
    lines = [
        BANNER, "",
        "# API reference", "",
        "Generated from the source tree by `docs/make_api.py`. The public",
        "surface is each module's `__all__`; anything else is internal and",
        "is not listed here.", "",
        "The names re-exported from the package root -- the ones in",
        "`stabilis.__all__` -- are the stable API and will not move without",
        "a version bump. They are marked **root** below. A name reached",
        "through a submodule path may move.", "",
        "| Page | Covers |",
        "| --- | --- |",
    ]
    for group, title, blurb in GROUPS:
        lines.append(f"| [{title}]({group}.md) | {blurb} |")
    lines += ["", "## Every public name", "",
              "| Name | Kind | Module | Summary |", "| --- | --- | --- | --- |"]
    rows: list[tuple[str, str]] = []
    for group, _, _ in GROUPS:
        for module in pages[group]:
            for entry in module.entries:
                root = " **root**" if entry.name in promised else ""
                summary = _first_line(entry.doc).replace("|", r"\|")
                anchor = anchors[group, module.dotted, entry.name]
                rows.append((
                    entry.name,
                    f"| [`{entry.name}`]({group}.md#{anchor})"
                    f"{root} | {entry.kind} | `stabilis.{module.dotted}` | "
                    f"{summary} |",
                ))
    lines += [row for _, row in sorted(rows, key=lambda r: r[0].lower())]
    missing = promised - {name for name, _ in rows} - {"__version__"}
    if missing:
        lines += ["", "Re-exported at the root but documented under their",
                  "defining module only: " +
                  ", ".join(f"`{n}`" for n in sorted(missing)) + "."]
    return "\n".join(lines).rstrip() + "\n"


def build() -> dict[Path, str]:
    """Path -> content for every generated file."""
    pages = collect()
    undocumented = [f"stabilis.{m.dotted}.{e.name}"
                    for mods in pages.values() for m in mods for e in m.entries
                    if not e.doc.strip() and e.kind in ("function", "class")]
    for name in undocumented:
        print(f"warning: no docstring for {name}", file=sys.stderr)
    files = {OUT / "index.md": render_index(pages, anchor_map(pages))}
    for group, title, blurb in GROUPS:
        files[OUT / f"{group}.md"] = render_page(group, title, blurb, pages[group])
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="do not write; exit 1 if the pages are stale")
    args = parser.parse_args(argv)
    files = build()
    if args.check:
        stale = [p for p, text in files.items()
                 if not p.is_file() or p.read_text(encoding="utf-8") != text]
        for path in stale:
            print(f"stale: {path}", file=sys.stderr)
        return 1 if stale else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")
    print(f"wrote {len(files)} pages to {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
