#!/usr/bin/env python3
"""Generate the reference input files for the Stable32 parity session.

Run from the repo root:

    python3 tests/data/stable32/generate.py

Rewrites everything in `inputs/` deterministically -- same seeds, same
bytes, every time. `inputs/MANIFEST.md` records the SHA-256 of each file so
the session's `PROVENANCE.md` can name exactly what was analysed.

**Why our own data rather than PHASE.DAT.** PHASE.DAT reaches us through
`allantools`, which is LGPL against this repo's MPL, and its own provenance
is a Stable32 distribution we cannot cite precisely. These files are ours:
MPL, reproducible from this script, and generated at a *known* h_alpha, so
Stable32's sigma columns can be checked against a value neither program
computed. That is worth more than matching a file everyone already has.

The run sheet asks for PHASE.DAT and the NBS suites too -- those are
fetched at run time from the URLs in `references.md` and are not committed.
"""

import hashlib
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "src"))

from stabilis.powerlaw_coeffs import avar_coeff  # noqa: E402
from stabilis.synth import ALPHA_NAMES, power_law_phase  # noqa: E402

HERE = Path(__file__).resolve().parent
INPUTS = HERE / "inputs"

# One record per power law, plus a drift case. Fixed seeds, fixed length.
# 4097 phase points = 4096 frequency points, a power of two, and long enough
# that the octave tau grid reaches m = 128 with real degrees of freedom.
N_FREQ = 4096
RATE_HZ = 1.0
H_ALPHA = 1.0e-24
SEEDS = {2: 20260801, 1: 20260802, 0: 20260803, -1: 20260804, -2: 20260805}
DRIFT_PER_S = 1.0e-13


def main() -> int:
    INPUTS.mkdir(exist_ok=True)
    rows = []
    for alpha, seed in SEEDS.items():
        ps = power_law_phase(N_FREQ, alpha, rate_hz=RATE_HZ,
                             rng=np.random.default_rng(seed), h_alpha=H_ALPHA)
        name = f"alpha{alpha:+d}.dat".replace("+", "p").replace("-", "m")
        rows.append(_write(name, ps.x, alpha, seed))

    # A drift record, where the expected ADEV is exact rather than
    # statistical: avar = D^2 tau^2/2, so Stable32's sigma column can be
    # checked against arithmetic with no noise in it at all.
    t = np.arange(N_FREQ + 1, dtype=np.float64) / RATE_HZ
    rows.append(_write("drift.dat", 0.5 * DRIFT_PER_S * t**2, None, None))

    (INPUTS / "MANIFEST.md").write_text(_manifest(rows), encoding="utf-8")
    print(f"wrote {len(rows)} files and MANIFEST.md to {INPUTS}")
    return 0


def _write(name: str, x: np.ndarray, alpha, seed) -> dict:
    path = INPUTS / name
    # One column, plain ASCII, no header -- what Stable32 reads without
    # any import dialog.
    #
    # %.15e does NOT round-trip float64: measured on 200k normal deviates,
    # 42% of them come back a bit or two different. 17 significant digits
    # is the guaranteed width and what `io/write.py` writes. This is left
    # at 15 anyway, deliberately: these files and their SHA-256s in
    # MANIFEST.md are the inputs Stable32 was actually run on, so changing
    # a digit here would silently invalidate every committed export in
    # outputs/. The text on disk is the reference, not the doubles that
    # produced it, and text -> float64 -> text is stable at this width.
    text = "\n".join(f"{v:.15e}" for v in x) + "\n"
    path.write_text(text, encoding="ascii", newline="\n")
    return {
        "name": name,
        "alpha": alpha,
        "seed": seed,
        "n": x.size,
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
    }


def _manifest(rows: list[dict]) -> str:
    tau0 = 1.0 / RATE_HZ
    out = [
        "# Reference inputs for the Stable32 parity session",
        "",
        "Generated by `generate.py` in this directory. Phase in seconds, one",
        "column, ASCII, LF line endings, `%.15e`. Regenerating reproduces",
        "these bytes exactly; if a SHA-256 below ever fails to match, the",
        "session that produced the outputs used different data and the",
        "outputs are not evidence about these files.",
        "",
        f"All records: `tau0 = {tau0:g} s`, {N_FREQ} frequency points,",
        f"`h_alpha = {H_ALPHA:g}` where applicable.",
        "",
        "| file | contents | expected sigma_y(tau) | SHA-256 |",
        "|---|---|---|---|",
    ]
    for r in rows:
        if r["alpha"] is None:
            what = f"linear drift D = {DRIFT_PER_S:g} /s"
            expect = "`D*tau/sqrt(2)`, **exact**"
        else:
            a = r["alpha"]
            what = f"{ALPHA_NAMES[a]} (alpha = {a:+d}), seed {r['seed']}"
            expect = f"`sqrt({_coeff_text(a)} * {H_ALPHA:g})`"
        out.append(f"| `{r['name']}` | {what} | {expect} | `{r['sha256']}` |")

    out += [
        "",
        "The expected column is the *ensemble* value, so a single record",
        "scatters around it -- by tens of percent at the longest tau. It is",
        "there so a gross disagreement is obvious, not as a pass criterion.",
        "`drift.dat` is the exception: that one is exact, and Stable32's",
        "sigma column should reproduce it to its printed precision.",
        "",
        "Worked expected values at a few tau, for the noise records",
        "(overlapping Allan deviation):",
        "",
        "| alpha | sigma_y(1 s) | sigma_y(16 s) | sigma_y(128 s) |",
        "|---|---|---|---|",
    ]
    for a in SEEDS:
        vals = avar_coeff(a, np.array([1.0, 16.0, 128.0]), 0.5 / tau0) * H_ALPHA
        cells = "  |  ".join(f"{v:.4e}" for v in np.sqrt(vals))
        out.append(f"| {a:+d} | {cells} |")
    out += [
        "",
        "and for `drift.dat`: `sigma_y(1 s)` = "
        f"{DRIFT_PER_S / np.sqrt(2):.4e}, `sigma_y(16 s)` = "
        f"{16 * DRIFT_PER_S / np.sqrt(2):.4e}, `sigma_y(128 s)` = "
        f"{128 * DRIFT_PER_S / np.sqrt(2):.4e}.",
        "",
        "Note the alpha = +1 and +2 rows assume `f_h` = Nyquist = "
        f"{0.5 / tau0:g} Hz. For alpha = +2 that is exact by construction; "
        "for alpha = +1 it is not, and the generated record sits about 3-5% "
        "above the tabulated value. See `theory/powerlaw.md`.",
        "",
        "**Two systematic offsets at short tau, which are not scatter and",
        "must not be read as a Stable32 disagreement.** The tabulated values",
        "are the continuum closed forms; a discretely-sampled process differs",
        "from them at small `m` by an exact and known factor:",
        "",
        "* alpha = -2 is high by `1 + 1/(2*m**2)` -- **+22% in deviation at",
        "  `tau = tau0`**, +6% at 2 tau0, gone by 16 tau0;",
        "* alpha = -1 is high by 44% in variance (20% in deviation) at",
        "  `tau = tau0`, since `sigma2(tau0) = 2*h_-1` exactly rather than",
        "  `2*ln2*h_-1`.",
        "",
        "Both are derived and tested in `theory/noise-types.md`. Stable32 is",
        "expected to reproduce the *record*, offsets and all, because they",
        "are in the data.",
    ]
    return "\n".join(out) + "\n"


def _coeff_text(alpha: int) -> str:
    return {
        2: "3*f_h/(4*pi^2*tau^2)",
        1: "[1.038+3*ln(2*pi*f_h*tau)]/(4*pi^2*tau^2)",
        0: "1/(2*tau)",
        -1: "2*ln2",
        -2: "(2*pi^2/3)*tau",
    }[alpha]


if __name__ == "__main__":
    raise SystemExit(main())
